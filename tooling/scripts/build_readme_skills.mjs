#!/usr/bin/env node
// Generates the layer and skill list of README.md from layers.json and the SKILL.md frontmatter of every own
// skill: one line and a link per skill, so the README never holds a second copy of what a skill is for.
// Usage: node tooling/scripts/build_readme_skills.mjs [--check] [--root <dir>]
// The list lives between the markers below; the rest of README.md is hand-written. --check writes nothing and
// exits 1 when the block is stale; the markers must exist (exit 2).
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const BEGIN = '<!-- layers:begin (generated by tooling/scripts/build_readme_skills.mjs from layers.json and the SKILL.md files; do not edit) -->';
export const END = '<!-- layers:end -->';
const MAX_LINE = 220;
// A source with more skills than this is summarised by its count, so one long list does not dominate the README.
const MAX_LISTED = 18;

/** The description of a SKILL.md as one string (plain, quoted or folded scalar). */
export function readDescription(text, label = 'SKILL.md') {
    const match = text.match(/^---\n([\s\S]*?)\n---\n/);
    if (!match) {
        throw new Error(`${label}: no frontmatter`);
    }
    const lines = match[1].split('\n');
    const start = lines.findIndex((line) => line.startsWith('description:'));
    if (start === -1) {
        throw new Error(`${label}: no description`);
    }
    let value = lines[start].slice('description:'.length).trim();
    if (/^[>|][+-]?$/.test(value)) {
        const folded = [];
        for (const line of lines.slice(start + 1)) {
            if (/^\S/.test(line)) {
                break;
            }
            folded.push(line.trim());
        }
        value = folded.join(' ');
    } else if (value.length > 1 && value.startsWith('"') && value.endsWith('"')) {
        value = value.slice(1, -1).replace(/\\(["\\])/g, '$1');
    } else if (value.length > 1 && value.startsWith("'") && value.endsWith("'")) {
        value = value.slice(1, -1).replace(/''/g, "'");
    }
    if (!value) {
        throw new Error(`${label}: empty description`);
    }
    return value;
}

/** The first sentence of a description, capped at one README line. */
export function firstSentence(description) {
    const flat = description.replace(/\s+/g, ' ').trim();
    const sentence = flat.match(/^(.+?[.!?])(?=\s+[A-Z`"'(]|$)/)?.[1] ?? flat;
    if (sentence.length <= MAX_LINE) {
        return sentence;
    }
    return `${sentence.slice(0, MAX_LINE).replace(/\s+\S*$/, '').replace(/[,;:(-]+$/, '')}…`;
}

const names = (skills) => skills.map((skill) => `\`${skill}\``).join(', ');

function sourceText(source) {
    const repo = `\`${source.repo.replace(/^git@github\.com:/, '').replace(/\.git$/, '')}\`${source.ref ? ` (\`${source.ref}\`)` : ''}`;
    const notes = [source.optional ? 'optional' : '', source.private ? 'private repository' : ''].filter(Boolean).join(', ');
    const list = source.skills.length > MAX_LISTED ? `${source.skills.length} skills` : names(source.skills);
    return `${repo}${notes ? ` (${notes})` : ''}: ${list}`;
}

export function renderBlock(root) {
    const manifest = JSON.parse(readFileSync(join(root, 'layers.json'), 'utf8'));
    const out = [];
    Object.entries(manifest.layers).forEach(([id, layer], index) => {
        const requires = layer.requires.length ? layer.requires.map((name) => `\`${name}\``).join(', ') : 'nothing';
        const where = layer.scope === 'project' ? 'project (committed with `skills-lock.json`)' : 'user (installed for the person)';
        out.push(`### ${index + 1}. \`${id}\` - ${layer.title}`, '', `${layer.description} Scope: ${where}. Requires: ${requires}.`, '');
        for (const skill of layer.skills ?? []) {
            const path = `skills/${id}/${skill}/SKILL.md`;
            if (!existsSync(join(root, path))) {
                throw new Error(`layers.json lists ${skill} in ${id}, but ${path} does not exist`);
            }
            out.push(`- [\`${skill}\`](${path}): ${firstSentence(readDescription(readFileSync(join(root, path), 'utf8'), path))}`);
        }
        for (const source of layer.sources ?? []) {
            out.push(`- ${sourceText(source)}`);
        }
        for (const [group, definition] of Object.entries(layer.groups ?? {})) {
            const detect = definition.detect?.map((entry) => `\`${entry}\``).join(', ');
            const tag = definition.default !== false ? '' : detect ? ` (named explicitly, or by \`project init\` for ${detect})` : ' (on request)';
            const content = definition.managedBy
                ? `installed by ${definition.managedBy}, not by the helper`
                : (definition.sources ?? []).map(sourceText).join('; ');
            out.push(`- Group \`${group}\`${tag}: ${content}`);
        }
        out.push('');
    });
    return `${BEGIN}\n\n${out.join('\n').trimEnd()}\n\n${END}`;
}

/** README text with the block between the markers replaced; throws when a marker is missing. */
export function applyBlock(readme, block) {
    const start = readme.indexOf(BEGIN);
    const end = readme.indexOf(END);
    if (start === -1 || end === -1 || end < start) {
        throw new Error(`README.md needs the markers ${BEGIN} and ${END}`);
    }
    return `${readme.slice(0, start)}${block}${readme.slice(end + END.length)}`;
}

function main() {
    const args = process.argv.slice(2);
    const rootIndex = args.indexOf('--root');
    const root = rootIndex >= 0 ? args[rootIndex + 1] : fileURLToPath(new URL('../..', import.meta.url));
    const file = join(root, 'README.md');
    let next;
    try {
        next = applyBlock(readFileSync(file, 'utf8'), renderBlock(root));
    } catch (error) {
        console.error(error.message);
        process.exit(2);
    }
    if (args.includes('--check')) {
        if (readFileSync(file, 'utf8') !== next) {
            console.error('The layer list of README.md is out of date. Run: node tooling/scripts/build_readme_skills.mjs');
            process.exit(1);
        }
        return;
    }
    writeFileSync(file, next);
    console.log('Updated the layer list of README.md');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
    main();
}
